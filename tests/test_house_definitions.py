"""Independent, definition-based verification of contracts/houses/cusps.json.

The fixture is generated by the Rust implementation (a parity fixture). These
tests do not reuse any implementation's house code: they recompute sidereal
time and obliquity from the documented IAU 2006 formulas (cross-checked here
against the ERFA reference values) and then verify the *defining geometric
property* of each house system for every cusp in the fixture:

* ASC lies on the eastern horizon; MC on the upper meridian.
* Placidus: cusps 11/12 (2/3) lie at 1/3 and 2/3 of their own diurnal
  (nocturnal) semi-arc measured from the meridian (horizon).
* Campanus: cusps lie on the great circles through the north and south
  points of the horizon dividing the prime vertical into 30-degree sectors.
* Equal / Whole Sign / Porphyry: their arithmetic definitions.
* Substituted systems carry Whole Sign cusps and a warning.
"""

import json
import math
import unittest
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parent.parent / "contracts"
FIXTURE = json.loads((CONTRACTS / "houses/cusps.json").read_text())
TRUE_FIXTURE = json.loads((CONTRACTS / "houses/cusps-true-equinox.json").read_text())
ERFA = json.loads((CONTRACTS / "reference/earth-orientation-erfa.json").read_text())["epochs"]
TOL = 1e-7  # degrees, geometric-identity tolerance


def norm(x):
    return x % 360.0


def sdiff(a, b):
    return (a - b + 180.0) % 360.0 - 180.0


def gmst_deg(jd_ut):
    d = jd_ut - 2451545.0
    t = d / 36525.0
    return norm(280.46061837 + 360.98564736629 * d + 0.000387933 * t * t - t ** 3 / 38710000.0)


def mean_obliquity_deg(jd):
    t = (jd - 2451545.0) / 36525.0
    return (84381.406 - 46.836769 * t - 0.0001831 * t ** 2 + 0.00200340 * t ** 3
            - 0.000000576 * t ** 4 - 0.0000000434 * t ** 5) / 3600.0


def ecliptic_to_equatorial(lon, eps):
    l, e = math.radians(lon), math.radians(eps)
    ra = math.degrees(math.atan2(math.sin(l) * math.cos(e), math.cos(l)))
    dec = math.degrees(math.asin(math.sin(e) * math.sin(l)))
    return norm(ra), dec


def horizon_vector(lon, eps, ramc, lat):
    """Unit vector (east, north, up) of an ecliptic point (latitude 0)."""
    ra, dec = ecliptic_to_equatorial(lon, eps)
    h = math.radians(ramc - ra)  # hour angle, west positive
    d, p = math.radians(dec), math.radians(lat)
    east = -math.cos(d) * math.sin(h)
    north = math.sin(d) * math.cos(p) - math.cos(d) * math.cos(h) * math.sin(p)
    up = math.sin(d) * math.sin(p) + math.cos(d) * math.cos(h) * math.cos(p)
    return east, north, up


class HouseDefinitionTests(unittest.TestCase):
    def test_sidereal_time_formula_agrees_with_erfa(self):
        for epoch in ERFA:
            # The implementations' classic UT-based GMST polynomial differs from
            # IAU 2006 gmst06 (whose polynomial runs on TT) by <= 0.15" over
            # 1950-2049; this is the source of the axis residuals vs ERFA.
            self.assertLess(abs(sdiff(gmst_deg(epoch["jd_utc"]), epoch["gmst_deg"])) * 3600, 0.2)
            self.assertLess(abs(mean_obliquity_deg(epoch["jd_tt"]) - epoch["mean_obliquity_deg"]) * 3600, 1e-3)

    def _cases(self):
        """Mean-convention cases (RAMC/obliquity recomputed here) and
        true-equinox cases (RAMC/obliquity as recorded, checked against ERFA
        in test_true_equinox_inputs_match_erfa)."""
        for case in FIXTURE["cases"]:
            jd, lat, lon = case["jd_ut"], case["latitude"], case["longitude"]
            yield case, norm(gmst_deg(jd) + lon), mean_obliquity_deg(jd), lat
        for case in TRUE_FIXTURE["cases"]:
            yield case, case["ramc_deg"], case["obliquity_deg"], case["latitude"]

    def test_true_equinox_inputs_match_erfa(self):
        by_utc = {e["utc"]: e for e in ERFA}
        for case in TRUE_FIXTURE["cases"]:
            erfa = by_utc[case["utc"]]
            with self.subTest(case=case["id"]):
                self.assertEqual((case["jd_ut"], case["jd_tt"]), (erfa["jd_utc"], erfa["jd_tt"]))
                # RAMC = GAST + east longitude; residual = GMST formula difference (<= 0.15").
                ramc_err = sdiff(case["ramc_deg"], erfa["gast_deg"] + case["longitude"]) * 3600
                self.assertLess(abs(ramc_err), 0.2)
                self.assertLess(abs(case["obliquity_deg"] - erfa["true_obliquity_deg"]) * 3600, 1e-3)

    def test_axes_satisfy_horizon_and_meridian_definitions(self):
        for case, ramc, eps, lat in self._cases():
            with self.subTest(case=case["id"]):
                e, _n, u = horizon_vector(case["axes"]["asc"], eps, ramc, lat)
                self.assertAlmostEqual(u, 0.0, delta=TOL)
                self.assertGreater(e, 0.0)  # eastern horizon
                ra_mc, _ = ecliptic_to_equatorial(case["axes"]["mc"], eps)
                self.assertAlmostEqual(sdiff(ra_mc, ramc), 0.0, delta=TOL)

    def test_placidus_cusps_trisect_their_semi_arcs(self):
        for case, ramc, eps, lat in self._cases():
            placidus = case["systems"]["Placidus"]
            if placidus["warnings"]:
                self.assertTrue(abs(lat) >= 90.0 - eps)  # documented polar fallback
                continue
            cusps = placidus["cusps"]
            for house, fraction, above in ((11, 1 / 3, True), (12, 2 / 3, True), (2, 1 / 3, False), (3, 2 / 3, False)):
                with self.subTest(case=case["id"], house=house):
                    ra, dec = ecliptic_to_equatorial(cusps[house - 1], eps)
                    dsa = math.degrees(math.acos(-math.tan(math.radians(lat)) * math.tan(math.radians(dec))))
                    east_of_meridian = norm(ra - ramc)  # 0..360, cusps 11..3 rise in the east
                    expected = fraction * dsa if above else dsa + fraction * (180.0 - dsa)
                    self.assertAlmostEqual(east_of_meridian, expected, delta=TOL)

    def test_campanus_cusps_lie_on_prime_vertical_divisions(self):
        for case, ramc, eps, lat in self._cases():
            cusps = case["systems"]["Campanus"]["cusps"]
            for house in range(1, 13):
                with self.subTest(case=case["id"], house=house):
                    e, _n, u = horizon_vector(cusps[house - 1], eps, ramc, lat)
                    angle = norm(math.degrees(math.atan2(u, e)))  # about the north-south axis
                    expected = norm(30.0 * (1 - house))  # cusp 1 = east point, 12 = 30 deg up, ...
                    # A great circle through N and S contains both theta and theta+180.
                    off_circle = (sdiff(angle, expected) + 90.0) % 180.0 - 90.0
                    self.assertAlmostEqual(off_circle, 0.0, delta=1e-6)

    def test_arithmetic_systems(self):
        for case, _ramc, _eps, _lat in self._cases():
            asc, mc = case["axes"]["asc"], case["axes"]["mc"]
            systems = case["systems"]
            with self.subTest(case=case["id"]):
                for i, cusp in enumerate(systems["Equal"]["cusps"]):
                    self.assertAlmostEqual(sdiff(cusp, asc + 30 * i), 0.0, delta=TOL)
                first = math.floor(asc / 30.0) * 30.0
                for i, cusp in enumerate(systems["Whole Sign"]["cusps"]):
                    self.assertAlmostEqual(sdiff(cusp, first + 30 * i), 0.0, delta=TOL)
                porphyry = systems["Porphyry"]["cusps"]
                self.assertAlmostEqual(sdiff(porphyry[0], asc), 0.0, delta=TOL)
                self.assertAlmostEqual(sdiff(porphyry[9], mc), 0.0, delta=TOL)
                arc = norm(norm(mc + 180) - asc)
                self.assertAlmostEqual(sdiff(porphyry[1], asc + arc / 3), 0.0, delta=TOL)

    def test_substituted_systems_are_whole_sign_with_warning(self):
        for case, *_ in self._cases():
            for name in ("Koch", "Regiomontanus", "Vehlow", "Alcabitius"):
                system = case["systems"][name]
                self.assertEqual(system["cusps"], case["systems"]["Whole Sign"]["cusps"])
                code = name.lower().replace(" ", "_")
                self.assertEqual(system["warnings"], [f"house_system_{code}_not_yet_supported: whole_sign_used"])


if __name__ == "__main__":
    unittest.main()
